import os

from framework.common.constants import RAW_DATASET_PATH, JSON_EXTENSION


ENVIRONMENT_FILE_NAME = "environment"

AIR_POLLUTION_RATIO_FILE_NAME = "airPollutionRatio"
NOISE_POLLUTION_RATIO_FILE_NAME = "noisePollutionRatio"
POLLUTION_RATIO_FILE_NAME = "pollutionRatio"
WATER_SUPPLY_RATIO_FILE_NAME = "waterSupplyRatio"

ENVIRONMENT_RAW_PATH = os.path.join(RAW_DATASET_PATH, ENVIRONMENT_FILE_NAME)


def generate_path(file_name: str) -> str:
    return ENVIRONMENT_RAW_PATH + os.sep + file_name + JSON_EXTENSION


AIR_POLLUTION_RATIO_PATH = generate_path(AIR_POLLUTION_RATIO_FILE_NAME)
NOISE_POLLUTION_RATIO_PATH = generate_path(NOISE_POLLUTION_RATIO_FILE_NAME)
POLLUTION_RATIO_PATH = generate_path(POLLUTION_RATIO_FILE_NAME)
WATER_SUPPLY_RATIO_PATH = generate_path(WATER_SUPPLY_RATIO_FILE_NAME)


__all__ = [
    'AIR_POLLUTION_RATIO_FILE_NAME',
    'AIR_POLLUTION_RATIO_PATH',
    'ENVIRONMENT_RAW_PATH',
    'NOISE_POLLUTION_RATIO_FILE_NAME',
    'NOISE_POLLUTION_RATIO_PATH',
    'POLLUTION_RATIO_FILE_NAME',
    'POLLUTION_RATIO_PATH',
    'WATER_SUPPLY_RATIO_FILE_NAME',
    'WATER_SUPPLY_RATIO_PATH',
]
