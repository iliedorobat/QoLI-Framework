import os

from framework.common.constants import RAW_DATASET_PATH, JSON_EXTENSION

OVERALL_EXPERIENCE_FILE_NAME = "overallExperience"

HAPPINESS_RATIO_FILE_NAME = "happinessRatio"
HIGH_SATISFACTION_RATIO_FILE_NAME = "highSatisfactionRatio"

OVERALL_EXPERIENCE_RAW_PATH = os.path.join(RAW_DATASET_PATH, OVERALL_EXPERIENCE_FILE_NAME)


def _generate_path(file_name: str) -> str:
    return os.path.join(OVERALL_EXPERIENCE_RAW_PATH, f"{file_name}{JSON_EXTENSION}")


HAPPINESS_RATIO_PATH = _generate_path(HAPPINESS_RATIO_FILE_NAME)
HIGH_SATISFACTION_RATIO_PATH = _generate_path(HIGH_SATISFACTION_RATIO_FILE_NAME)


__all__ = [
    "OVERALL_EXPERIENCE_FILE_NAME",
    "HAPPINESS_RATIO_FILE_NAME",
    "HIGH_SATISFACTION_RATIO_FILE_NAME",
    "OVERALL_EXPERIENCE_RAW_PATH",
    "HAPPINESS_RATIO_PATH",
    "HIGH_SATISFACTION_RATIO_PATH",
]
